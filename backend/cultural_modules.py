def get_all_cultural_origins():
    """Get all cultural origin modules."""
    return CULTURAL_ORIGINS

def get_cultural_origin(culture_key: str):
    """Get a specific cultural origin by key."""
    return CULTURAL_ORIGINS.get(culture_key)

def list_cultural_origin_names():
    """List all available cultural origins for UI display."""
    return [
        {
            "key": key,
            "name": culture["name"],
            "regions": culture["regions"]
        }
        for key, culture in CULTURAL_ORIGINS.items()
    ]

def build_culturally_enhanced_prompt(base_prompt: str, culture_key: str) -> str:
    """
    Enhance base prompt with cultural authenticity details.
    All content in English for user accessibility.
    
    Args:
        base_prompt: The base character generation prompt
        culture_key: Specific cultural origin key
        
    Returns:
        Enhanced prompt with cultural details
    """
    culture = get_cultural_origin(culture_key)
    if not culture:
        return base_prompt
    
    enhanced_prompt = f"""{base_prompt}

{culture['cultural_elements']}

IMPORTANT: All dialogue, thoughts, and narration should be in ENGLISH, even if the character speaks another language natively. You may reference their multilingual abilities, but present everything in English for reader accessibility.
"""
    return enhanced_prompt
